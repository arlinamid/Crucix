#!/usr/bin/env node
// Bundle dashboard/public client assets into a compressed embedded module for SEA standalone binary.
// Usage: node scripts/bundle-dashboard-assets.mjs

import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const publicDir = join(ROOT, 'dashboard', 'public');
const outFile = join(ROOT, 'lib', 'embedded-dashboard.mjs');

function collectFiles(dir, base = '') {
  let entries = {};
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${item.name}` : item.name;
    const full = join(dir, item.name);
    if (item.isDirectory()) {
      Object.assign(entries, collectFiles(full, rel));
    } else {
      entries[rel] = readFileSync(full).toString('base64');
    }
  }
  return entries;
}

const files = collectFiles(publicDir);
const fileCount = Object.keys(files).length;
const jsonStr = JSON.stringify(files);
const gzipped = zlib.gzipSync(Buffer.from(jsonStr), { level: 9 });
const b64 = gzipped.toString('base64');

const code = `// Auto-generated by scripts/bundle-dashboard-assets.mjs — DO NOT EDIT DIRECTLY
// Contains gzipped bundle of dashboard/public client assets (${fileCount} files)
// for 100% self-contained standalone execution (SEA).

export const DASHBOARD_ASSET_COUNT = ${fileCount};
export const DASHBOARD_ASSETS_GZIP_B64 =
  ${JSON.stringify(b64)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, code, 'utf8');

const rawKb = (jsonStr.length / 1024).toFixed(1);
const gzipKb = (gzipped.length / 1024).toFixed(1);
console.log(`✅ lib/embedded-dashboard.mjs generated: ${fileCount} files (${rawKb} KB -> ${gzipKb} KB gzipped)`);
