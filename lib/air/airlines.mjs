export const AIRLINES = Object.freeze(ROWS.map(([icao, iata, name, aliases, shorts]) => Object.freeze({ icao, iata, name, aliases, shorts })));
const BY_ICAO = new Map(AIRLINES.map(airline => [airline.icao, airline]));
const BY_IATA = new Map(AIRLINES.map(airline => [airline.iata, airline]));

export const airlineByIcao = code => typeof code === 'string' ? BY_ICAO.get(code.toUpperCase()) ?? null : null;
export const airlineByIata = code => typeof code === 'string' ? BY_IATA.get(code.toUpperCase()) ?? null : null;

/** The flight number of an airline callsign whose number is all digits (DLH400 -> LH400, DLH0400 -> LH400), or null. */
export function flightOfCallsign(callsign) {
  const match = /^([A-Z]{3})0*(\d{1,4})$/.exec(String(callsign || '').trim().toUpperCase());
  if (!match) return null;
  const airline = BY_ICAO.get(match[1]);
  return airline ? { flight: `${airline.iata}${match[2]}`, airline } : null;
}
